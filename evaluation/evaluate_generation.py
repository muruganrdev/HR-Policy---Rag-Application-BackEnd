# 2. Evaluation Helper Functions
# ------------------------------------------------------------

def evaluate_answer(answer: str, expected_keywords: List[str]) -> Dict[str, Any]:
    """
    Performs case-insensitive deterministic keyword matching on the generated answer.

    Args:
        answer: The text generated by the RAG system.
        expected_keywords: List of key phrases expected in the answer.

    Returns:
        A dictionary with keyword-level match status, counts, percentage, and pass/fail flag.
    """
    answer_lower = answer.lower()
    keyword_matches = {}
    matched_count = 0
    missing_keywords = []

    for kw in expected_keywords:
        kw_lower = kw.lower()
        is_matched = kw_lower in answer_lower
        keyword_matches[kw] = is_matched

        if is_matched:
            matched_count += 1
        else:
            missing_keywords.append(kw)

    total_keywords = len(expected_keywords)
    match_percentage = (matched_count / total_keywords * 100.0) if total_keywords > 0 else 0.0

    # Question PASS if at least one expected keyword is found in the generated answer
    is_pass = matched_count >= 1 if total_keywords > 0 else True

    return {
        "keyword_matches": keyword_matches,
        "matched_count": matched_count,
        "total_keywords": total_keywords,
        "match_percentage": match_percentage,
        "missing_keywords": missing_keywords,
        "is_pass": is_pass
    }


def check_grounding(retrieved_chunks: List[Dict[str, Any]], answer: str, expected_keywords: List[str]) -> Dict[str, Any]:
    """
    Basic deterministic keyword-based grounding check:
    Verifies whether expected keywords appear in the retrieved context,
    and whether those keywords also appear in the generated answer.

    Args:
        retrieved_chunks: List of candidate chunks returned by the retriever.
        answer: The text generated by the LLM.
        expected_keywords: List of key phrases expected for the question.

    Returns:
        Dictionary containing keyword-level context and answer presence.
    """
    combined_context = " ".join([c.get("content", "") for c in retrieved_chunks]).lower()
    answer_lower = answer.lower()

    grounding_details = {}
    grounded_keywords = []

    for kw in expected_keywords:
        kw_lower = kw.lower()
        in_context = kw_lower in combined_context
        in_answer = kw_lower in answer_lower

        grounding_details[kw] = {
            "in_retrieved_context": in_context,
            "in_generated_answer": in_answer,
            "is_grounded": in_context and in_answer
        }

        if in_context and in_answer:
            grounded_keywords.append(kw)

    return {
        "grounding_details": grounding_details,
        "grounded_keywords": grounded_keywords
    }


def evaluate_question(question_data: Dict[str, Any]) -> Dict[str, Any]:
    """
    Executes end-to-end RAG question answering, retrieves candidate chunks,
    and evaluates generation quality and grounding.

    Args:
        question_data: Item from EVALUATION_DATASET.

    Returns:
        Evaluation results dictionary for aggregate reporting.
    """
    q_id = question_data["id"]
    question = question_data["question"]
    expected_source = question_data["expected_source"]
    expected_keywords = question_data.get("expected_keywords", [])

    # 1. Execute existing RAG pipeline to generate answer
    rag_result = ask_question(question)
    generated_answer = rag_result.get("answer", "").strip()
    sources = rag_result.get("sources", [])

    # 2. Retrieve context chunks using existing search function for grounding check
    retrieved_chunks = search(question)

    # 3. Evaluate answer content against expected keywords
    answer_eval = evaluate_answer(generated_answer, expected_keywords)

    # 4. Check basic keyword-based grounding
    grounding_eval = check_grounding(retrieved_chunks, generated_answer, expected_keywords)

    # Display question evaluation report
    print("=" * 60)
    print(f"Question ID: {q_id}")
    print(f"Question: {question}")
    print(f"Expected Source: {expected_source}")
    print("=" * 60)

    print("\n--- Generated Answer ---")
    print(generated_answer)

    print("\n--- Retrieved Sources ---")
    if sources:
        for s in sources:
            print(f"- {s.get('source')} (Chunk {s.get('chunk')})")
    else:
        print("None (No chunks passed threshold or casual response)")

    print("\n--- Expected Keywords ---")
    print(", ".join(expected_keywords) if expected_keywords else "None specified")

    print("\n--- Keyword Match in Answer ---")
    for kw, matched in answer_eval["keyword_matches"].items():
        status_str = "YES" if matched else "NO"
        print(f"- {kw}: {status_str}")

    print(f"\nKeyword Match Count     : {answer_eval['matched_count']} / {answer_eval['total_keywords']}")
    print(f"Keyword Match Percentage: {answer_eval['match_percentage']:.2f}%")
    print(f"Question Result         : {'PASS' if answer_eval['is_pass'] else 'FAIL'}")

    print("\n--- Basic Keyword-Based Grounding Check ---")
    for kw, details in grounding_eval["grounding_details"].items():
        in_ctx = "YES" if details["in_retrieved_context"] else "NO"
        in_ans = "YES" if details["in_generated_answer"] else "NO"
        is_grd = "YES" if details["is_grounded"] else "NO"
        print(f"- '{kw}': In Context={in_ctx}, In Answer={in_ans} -> Grounded={is_grd}")

    print("-" * 60 + "\n")

    return {
        "id": q_id,
        "question": question,
        "expected_source": expected_source,
        "answer": generated_answer,
        "sources": sources,
        "expected_keywords": expected_keywords,
        "matched_count": answer_eval["matched_count"],
        "total_keywords": answer_eval["total_keywords"],
        "missing_keywords": answer_eval["missing_keywords"],
        "is_pass": answer_eval["is_pass"],
        "error": None
    }


# ------------------------------------------------------------
# 3. Main Evaluation Runner
# ------------------------------------------------------------

def run_evaluation() -> None:
    """
    Iterates over all questions in EVALUATION_DATASET, collects metrics,
    and prints the final generation evaluation summary.
    """
    print("=" * 60)
    print("WEEK 4 ANSWER GENERATION EVALUATION")
    print("=" * 60)
    print(f"Total Benchmark Questions: {len(EVALUATION_DATASET)}\n")

    total_questions = len(EVALUATION_DATASET)
    passed_answers = 0
    failed_answers = 0
    total_expected_keywords_all = 0
    total_matched_keywords_all = 0

    partial_or_failed_questions = []

    for item in EVALUATION_DATASET:
        q_id = item["id"]
        try:
            res = evaluate_question(item)

            if res["is_pass"]:
                passed_answers += 1
            else:
                failed_answers += 1

            total_expected_keywords_all += res["total_keywords"]
            total_matched_keywords_all += res["matched_count"]

            # If there are any missing keywords, record for partial/failed breakdown
            if res["missing_keywords"]:
                partial_or_failed_questions.append({
                    "id": res["id"],
                    "question": res["question"],
                    "expected_source": res["expected_source"],
                    "answer": res["answer"],
                    "missing_keywords": res["missing_keywords"],
                    "is_pass": res["is_pass"]
                })

        except Exception as exc:
            failed_answers += 1
            print(f"Evaluation failed for question {q_id}: {exc}")
            partial_or_failed_questions.append({
                "id": q_id,
                "question": item.get("question", "N/A"),
                "expected_source": item.get("expected_source", "N/A"),
                "answer": f"ERROR: {exc}",
                "missing_keywords": item.get("expected_keywords", []),
                "is_pass": False
            })

    # Overall keyword match rate across all questions
    overall_keyword_match_rate = (
        (total_matched_keywords_all / total_expected_keywords_all * 100.0)
        if total_expected_keywords_all > 0 else 0.0
    )

    # Print Final Summary Block
    print("=" * 60)
    print("WEEK 4 GENERATION EVALUATION SUMMARY")
    print("=" * 60)
    print(f"Total Questions       : {total_questions}")
    print(f"Passed Answers        : {passed_answers}")
    print(f"Failed Answers        : {failed_answers}")
    print(f"Keyword Match Rate    : {overall_keyword_match_rate:.2f}%")
    print("=" * 60)

    # Print Partial / Failed Questions Section
    print("\n" + "=" * 60)
    print("QUESTIONS WITH PARTIAL / FAILED KEYWORD MATCHES")
    print("=" * 60)
    if partial_or_failed_questions:
        for q in partial_or_failed_questions:
            status_text = "PARTIAL PASS" if q["is_pass"] else "FAIL"
            print(f"\n[Question {q['id']}] ({status_text})")
            print(f"Question        : {q['question']}")
            print(f"Expected Source : {q['expected_source']}")
            print(f"Missing Keywords: {', '.join(q['missing_keywords'])}")
            print("Generated Answer:")
            print(q["answer"].strip())
            print("-" * 60)
    else:
        print("None (All questions matched 100% of expected keywords).")

    print("=" * 60)


if __name__ == "__main__":
    run_evaluation()
